package com.pfm.model;

import java.util.List;

public class Admin extends AppUser implements Reportable {

    public Admin(int id, String name, String email, String passwordHash) {
        super(id, name, email, passwordHash, Role.ADMIN);
    }

    @Override
    public String getDashboardSummary() {
        return "Admin Dashboard: User Management, Financial Data Security, "
                + "System Settings, Financial Overview, User Feedback";
    }

    @Override
    public List<String> getPermissions() {
        return List.of("MANAGE_USERS", "MANAGE_SECURITY", "MANAGE_SETTINGS",
                "VIEW_PLATFORM_OVERVIEW", "VIEW_FEEDBACK");
    }

    @Override
    public String generateReport() {
        return "Platform report generated by admin " + getName();
    }
}